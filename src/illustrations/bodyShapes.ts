/**
 * 部位をハイライトする人の図（前と後ろ）の形。どちらも幅100・高さ156の座標で、
 * 体の中心は x=50。左半分を描いて、mirror で右半分を作る。
 */

/** 左半分のパスの x を 100 - x にして右半分にする（M/L/C/Q だけのパス用） */
function mirror(d: string) {
  let isX = true;
  return d.replace(/-?\d+(\.\d+)?/g, (n) => {
    const v = isX ? String(Math.round((100 - Number(n)) * 100) / 100) : n;
    isX = !isX;
    return v;
  });
}
const both = (d: string) => [d, mirror(d)];

export interface Region {
  part: BodyPart;
  d: string;
}
const region = (part: BodyPart, d: string): Region[] => both(d).map((x) => ({ part, d: x }));

