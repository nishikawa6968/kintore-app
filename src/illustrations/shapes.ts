/** 左右対称の図形を作る：左半分のパスの x を 100 - x にして右半分にする */
function mirror(d: string) {
  let isX = true;
  return d.replace(/-?\d+(\.\d+)?/g, (n) => {
    const v = isX ? String(Math.round((100 - Number(n)) * 100) / 100) : n;
    isX = !isX;
    return v;
  });
}

